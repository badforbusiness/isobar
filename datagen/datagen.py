"""
Project ISOBAR — Synthetic Asset Register Generator
===================================================

This module generates synthetic credit asset portfolios for testing and validating
the ISOBAR Inverse Risk-Weighted Asset (RWA) Portfolio Shaping Engine.

Domain & Financial Rationale
----------------------------
1. Regulatory Framework:
   Credit risk capital calculations follow the Basel II/III Internal Ratings-Based (IRB)
   Advanced Approach using the Asymptotic Single Risk Factor (ASRF) / Vasicek model.
   Under IRB, regulatory capital requirement K is a non-linear function of:
     - Probability of Default (PD)
     - Loss Given Default (LGD)
     - Effective Maturity (M)
     - Asset Class (Corporate, SME, Retail-Mortgage)

   The Risk Weight (RW) is K * 12.5, converting capital fraction into RWA multiplier:
     RWA_i = EAD_i * RW_i

2. Decoupled Architecture & Precalculated Risk Weights:
   To enable rapid optimization in both classical solvers (e.g. SLSQP) and quantum samplers
   (Simulated Annealing / D-Wave QUBO), each asset bucket pre-calculates its IRB Risk Weight
   (`precalc_rw`) at data generation time. Solvers evaluate linear RWA contributions without
   re-evaluating heavy Gaussian CDFs/quantiles inside optimization inner loops.

3. Credit Rating Grade Calibration & Intra-Grade Heterogeneity:
   Rating grades (AAA through CCC) represent standardized credit risk bands with base PD
   midpoints defined by Basel calibration benchmarks. Within each asset class's eligible
   rating grades, bucket PDs are generated by adding small stochastic noise to the grade's
   base PD and clamping to the asset class's allowed `pd_range`.

4. Origination Limits & Search Space Definition:
   Each asset bucket is assigned a baseline Exposure at Default (`ead_baseline`).
   Policy bounds define origination floors and ceilings:
     - ead_min_limit = ead_baseline * ead_min_factor (policy floor, e.g. 50% of baseline)
     - ead_max_limit = ead_baseline * ead_max_factor (policy ceiling, e.g. 200% of baseline)

   These limits construct bounded decision intervals X_i in [ead_min_limit_i, ead_max_limit_i]
   for classical and quantum portfolio shaping algorithms.
"""

